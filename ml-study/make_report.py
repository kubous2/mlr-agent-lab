"""Write ml-study/report.html from the saved results (every number is read from files, none retyped).

Run from the repository root:  uv run python ml-study/make_report.py
"""
from html import escape

from report_data import (HERE, SCATTER, confusion_html, cv_table, f3, html_table, image_data_uri,
                         load_all, test_table)

OUT = HERE / "report.html"

CSS = """
body { font-family: system-ui, sans-serif; max-width: 920px; margin: 2rem auto; padding: 0 1rem;
       color: #1f2328; line-height: 1.5; }
h1 { margin-bottom: .2rem; } h2 { margin-top: 2.2rem; border-bottom: 1px solid #d0d7de; padding-bottom: .3rem; }
.sub { color: #59636e; margin-top: 0; }
.kpis { display: flex; gap: 1rem; flex-wrap: wrap; margin: 1.2rem 0; }
.kpi { border: 1px solid #d0d7de; border-radius: 8px; padding: .7rem 1rem; min-width: 150px; }
.kpi .v { font-size: 1.7rem; font-weight: 600; } .kpi .l { color: #59636e; font-size: .9rem; }
.tbl { border-collapse: collapse; margin: .8rem 0; font-variant-numeric: tabular-nums; }
.tbl th, .tbl td { border-bottom: 1px solid #d0d7de; padding: .35rem .7rem; text-align: right; }
.tbl th:first-child, .tbl td:first-child { text-align: left; }
.tbl thead th { background: #f6f8fa; }
.confusion td.hit { background: #dafbe1; font-weight: 600; }
img { max-width: 100%; border: 1px solid #d0d7de; border-radius: 6px; }
.note { color: #59636e; font-size: .92rem; }
"""


def kpi(value, label):
    return f'<div class="kpi"><div class="v">{value}</div><div class="l">{escape(label)}</div></div>'


def build(d):
    counts = ", ".join(f"{n} {c}" for c, n in d["class_counts"].items())
    recall = ", ".join(f"{c} {f3(r)}" for c, r in d["recall"].items())
    noise = d["noise_in_test"]
    noise_lines = ", ".join(str(x) for x in noise["line"])
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><title>Leaf classifier: results</title>
<style>{CSS}</style></head><body>
<h1>Leaf classifier: results</h1>
<p class="sub">Which classifier best predicts the tree type from leaf height and width, and how well does it do on unseen data?</p>

<div class="kpis">
{kpi(f3(d["test_ba"]), f"test balanced accuracy, {d['chosen']}")}
{kpi(f3(d["cv_mean"]), "cross-validated balanced accuracy")}
{kpi(f3(d["base_test"]), "baseline (always the largest class)")}
{kpi(f'{d["gap"]:+.3f}', "test minus CV")}
</div>

<h2>Data</h2>
<p><code>{d["csv_name"]}</code>: {d["n_rows"]} rows ({counts}). After removing {d["n_dupes"]} exact duplicate rows,
{d["n_dedup"]} rows were split {100 - d["test_pct"]} / {d["test_pct"]} %, stratified by class (seed {d["seed"]}),
into {d["n_train"]} training rows and {d["n_test"]} test rows.</p>
<img src="{image_data_uri(SCATTER)}" alt="Scatter plot of leaf height against leaf width, coloured by tree type">

<h2>Model comparison (cross-validation, training rows only)</h2>
<p>{d["n_models"]} models and the baseline, {d["n_grid"]} grid points in total, each scored with {d["n_folds"]}-fold
stratified cross-validation on balanced accuracy.</p>
{html_table(cv_table(d))}
<p>The baseline scores {f3(d["base_cv"])}. The real models range from {f3(d["real_min"])} to {f3(d["real_max"])},
a spread smaller than their CV standard deviations ({f3(d["real_std_min"])}–{f3(d["real_std_max"])}).
Models within {d["margin"]} of the best ({", ".join(d["tied"])}) count as tied and the simplest wins:
<b>{d["chosen"]} ({d["chosen_params"]})</b>.</p>

<h2>Test set (used once)</h2>
{html_table(test_table(d))}
<p>On the {d["n_test"]} test rows {d["chosen"]} reaches a balanced accuracy of <b>{f3(d["test_ba"])}</b>
(accuracy {f3(d["test_acc"])}, macro F1 {f3(d["test_f1"])}), {abs(d["gap"]):.3f} below its CV estimate of
{f3(d["cv_mean"])} ± {f3(d["cv_std"])}. The baseline scores {f3(d["base_test"])}.</p>

<h3>Confusion matrix ({escape(d["chosen"])}, test set)</h3>
{confusion_html(d)}
<p>Recall per class: {recall}. The weakest class is <b>{d["weakest"]}</b>; {d["weakest_as"][1]} of its test rows were
predicted as {d["weakest_as"][0]}. {d["n_wrong"]} of {d["n_test"]} test rows
were predicted wrong.</p>

<h2>Notes</h2>
<p>{len(noise)} of the {d["n_noise"]} suspicious rows from the data report (conflicting labels or a cherry inside the
maple cluster) landed in the test set (file lines {noise_lines}); {d["noise_wrong"]} of them were predicted wrong.</p>
<p class="note">Generated by <code>ml-study/make_report.py</code> from <code>ml-study/results/*.csv</code>,
<code>ml-study/figures/scatter.png</code> and <code>{d["csv_name"]}</code>.</p>
</body></html>
"""


def main():
    OUT.write_text(build(load_all()), encoding="utf-8")
    print(f"Saved {OUT}")


if __name__ == "__main__":
    main()
